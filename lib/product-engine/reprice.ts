/**
 * What a change of reference rate does to a loan's schedule. Pure: lib/product-engine/reprice-loan.ts writes it.
 *
 * The new rate applies from the first period that STARTS on or after the day it took effect: the period running on that day
 * keeps its amount, so nobody's next instalment is re-cut mid-period and no period is split between two rates. Of the rows
 * from there on, only those still untouched change: the longest run at the end of the schedule of rows not yet due, PENDING,
 * nothing paid. A row paid in advance ends the run, and everything before it stands. So does a row the common-law cap has reduced: its
 * interest stopped by law, not by the rate, and the charge sync owns both of its figures.
 *
 * The run is regenerated by the same split as a new loan on the balance that bears interest: principal is conserved to the cent (the
 * last row clears), the balloon stays on the last row, the rows of a principal-only grace still to come stay interest-only. What a loan
 * change carried onto a row (arrears principal, earned interest) is not repriced: it stays on that row.
 * Due dates, fees and credit-life premiums do not move.
 */
import { sastCalendarDate } from "@/lib/date/sast"
import { split } from "./schedule"
import type { Frequency, RepaymentStructure } from "./types"

export interface StoredRow {
  id: string
  installmentNo: number
  dueDate: Date
  principalDue: number
  interestDue: number
  feesDue: number
  creditLifePremiumDue: number
  totalDue: number
  totalPaid: number
  status: string
  /** Set on a row the common-law cap has reduced (lib/asset-finance/common-law-interest.ts). */
  commonLawContractualInterestDue?: number | null
  /** What a loan change carried onto the row (lib/loan-changes/plan.ts): arrears principal that bears no interest, and interest already earned. */
  carriedPrincipalDue?: number
  carriedInterestDue?: number
}

export interface RepriceInput {
  /** In instalment order. */
  rows: StoredRow[]
  startDate: Date
  frequency: Frequency
  structure: RepaymentStructure
  balloonCents: number
  newRatePm: number
  /** SAST day the reference took effect. */
  effectiveDate: string
  /** SAST day of the run. */
  today: string
}

export interface RepricePlan {
  updates: Array<{ id: string; principalDue: number; interestDue: number; totalDue: number }>
  /** New interest less old, what the loan's totals move by. */
  interestDelta: number
}

export function planReprice(input: RepriceInput): RepricePlan | null {
  const { rows, startDate, frequency, structure, effectiveDate, today, newRatePm, balloonCents } = input
  let first = rows.length
  for (let i = rows.length - 1; i >= 0; i--) {
    const row = rows[i]!
    const periodStart = i === 0 ? startDate : rows[i - 1]!.dueDate
    if (row.commonLawContractualInterestDue != null || row.status !== "PENDING" || row.totalPaid !== 0 || sastCalendarDate(row.dueDate) <= today || sastCalendarDate(periodStart) < effectiveDate) break
    first = i
  }
  const tail = rows.slice(first)
  // Only what bears interest is priced. What a change carried stands on its row, whatever the rate: it is added back after.
  const bearing = (row: StoredRow) => row.principalDue - (row.carriedPrincipalDue ?? 0)
  const balance = tail.reduce((a, r) => a + bearing(r), 0)
  if (tail.length === 0 || balance <= 0) return null

  const lead = structure === "AMORTISING" ? tail.findIndex((r) => bearing(r) > 0) : 0
  const { principal, interest } = split({
    principalCents: balance, interestRatePm: newRatePm, interestModel: "REDUCING_BALANCE", monthlyServiceFeeCents: 0, startDate, balloonCents: Math.min(balloonCents, balance),
    terms: { frequency, structure, graceKind: lead > 0 ? "PRINCIPAL_ONLY" : "NONE", graceInstalments: lead, instalments: tail.length },
  })
  const updates = tail.map((row, i) => {
    const principalDue = principal[i]! + (row.carriedPrincipalDue ?? 0)
    const interestDue = interest[i]! + (row.carriedInterestDue ?? 0)
    return { id: row.id, principalDue, interestDue, totalDue: principalDue + interestDue + row.feesDue + row.creditLifePremiumDue }
  })
  return { updates, interestDelta: updates.reduce((a, u, i) => a + u.interestDue - tail[i]!.interestDue, 0) }
}
