/**
 * Entity documents for the asset-finance demo seed: synthetic one-page PDFs
 * uploaded through the same parser and writer as the staff upload route
 * (parseEntityDocumentForm → storeEntityDocument: MIME, size and magic-byte
 * checks, storage, sha256, audit), verified and set as classifier evidence as
 * the verify and financials-evidence routes do. Idempotent: a live document of
 * the same type (and deal) is reused.
 */
import type { EntityDocumentType } from "@prisma/client"
import { PDFDocument, StandardFonts } from "pdf-lib"
import { prisma } from "@/lib/prisma"
import { AuditAction, logAuditStrict } from "@/lib/audit"
import { parseEntityDocumentForm, storeEntityDocument, type ParsedEntityUpload } from "@/lib/asset-finance/entity-document-io"
import { invalidFinancialsEvidenceIds, lockBusinessEntity, STAFF_UPLOAD_DOC_TYPES } from "@/lib/asset-finance/entity-documents"
import { nullableFigureFromDb } from "@/lib/asset-finance/big-cents"

export interface SeedActor {
  id: string
  email: string
}

/** A one-page PDF that says, on its face, that it is synthetic. */
async function syntheticPdf(title: string): Promise<Uint8Array<ArrayBuffer>> {
  const doc = await PDFDocument.create()
  const page = doc.addPage([595, 842])
  const font = await doc.embedFont(StandardFonts.Helvetica)
  page.drawText("SAMPLE DOCUMENT - DEMO DATA, NOT A REAL RECORD", { x: 50, y: 780, size: 14, font })
  page.drawText(title, { x: 50, y: 750, size: 12, font })
  page.drawText("Generated by the CredaFlow demo seed (prisma/seed/asset-finance.ts).", { x: 50, y: 730, size: 9, font })
  // A fresh ArrayBuffer-backed copy: File wants ArrayBuffer, not ArrayBufferLike.
  return new Uint8Array(await doc.save())
}

/** A synthetic PDF, parsed exactly as an upload route parses its multipart body. */
export async function syntheticUpload(
  docType: EntityDocumentType,
  title: string,
  allowed: readonly EntityDocumentType[],
  dealId: string | null,
): Promise<ParsedEntityUpload> {
  const form = new FormData()
  form.set("docType", docType)
  if (dealId) form.set("dealId", dealId)
  form.set("file", new File([await syntheticPdf(title)], `${docType.toLowerCase()}-sample.pdf`, { type: "application/pdf" }))
  const parsed = await parseEntityDocumentForm(new Request("http://seed.invalid/upload", { method: "POST", body: form }), allowed, {
    allowDeal: dealId !== null,
  })
  if ("error" in parsed) throw new Error(`Seed upload of ${docType} refused: ${parsed.error}`)
  return parsed.upload
}

/** The entity's live staff document of this type (on this deal), uploading it if missing. */
export async function ensureDocument(
  tenantId: string,
  actor: SeedActor,
  entityId: string,
  docType: EntityDocumentType,
  title: string,
  dealId: string | null = null,
): Promise<string> {
  const existing = await prisma.entityDocument.findFirst({
    where: { tenantId, entityId, docType, dealId, deletedAt: null, uploadedByType: "staff" },
    select: { id: true },
  })
  if (existing) return existing.id
  const upload = await syntheticUpload(docType, title, STAFF_UPLOAD_DOC_TYPES, dealId)
  const stored = await storeEntityDocument({ tenantId, entityId, upload, uploader: { type: "staff", id: actor.id, email: actor.email } })
  return stored.id
}

/** Mark a document verified, as POST …/documents/[documentId]/verify does; a verified one is left alone. */
export async function verifyDocument(tenantId: string, actor: SeedActor, entityId: string, documentId: string): Promise<void> {
  await prisma.$transaction(async (tx) => {
    const doc = await tx.entityDocument.findFirst({
      where: { id: documentId, entityId, tenantId, deletedAt: null },
      select: { id: true, docType: true, verifiedAt: true },
    })
    if (!doc) throw new Error(`Seed: document ${documentId} not found`)
    if (doc.verifiedAt) return
    const verifiedAt = new Date()
    const { count } = await tx.entityDocument.updateMany({
      where: { id: doc.id, tenantId, verifiedAt: null, deletedAt: null },
      data: { verifiedAt, verifiedById: actor.id },
    })
    if (count === 0) return
    await logAuditStrict({
      tenantId, userId: actor.id, userEmail: actor.email,
      action: AuditAction.ENTITY_DOCUMENT_VERIFIED, entity: "EntityDocument", entityId: doc.id,
      newValue: { businessEntityId: entityId, docType: doc.docType, verifiedAt: verifiedAt.toISOString() },
    }, tx)
  })
}

/** Set the classifier's financials evidence, as PUT …/financials-evidence does. Unchanged evidence writes nothing. */
export async function setFinancialsEvidence(tenantId: string, actor: SeedActor, entityId: string, documentIds: string[]): Promise<void> {
  await prisma.$transaction(async (tx) => {
    if (!(await lockBusinessEntity(tx, tenantId, entityId))) throw new Error(`Seed: entity ${entityId} not found`)
    const entity = await tx.businessEntity.findFirstOrThrow({
      where: { id: entityId, tenantId },
      select: { financialsEvidenceIds: true, annualTurnover: true, totalAssetValue: true },
    })
    if (entity.financialsEvidenceIds.join("|") === documentIds.join("|")) return
    const invalid = await invalidFinancialsEvidenceIds(tx, tenantId, entityId, documentIds)
    if (invalid.length > 0) throw new Error(`Seed: not verified AFS evidence of the entity: ${invalid.join(", ")}`)
    await tx.businessEntity.update({ where: { id: entityId, tenantId }, data: { financialsEvidenceIds: documentIds } })
    await logAuditStrict({
      tenantId, userId: actor.id, userEmail: actor.email,
      action: AuditAction.ENTITY_FINANCIALS_EVIDENCE_SET, entity: "BusinessEntity", entityId,
      oldValue: { financialsEvidenceIds: entity.financialsEvidenceIds },
      newValue: {
        financialsEvidenceIds: documentIds,
        annualTurnover: nullableFigureFromDb(entity.annualTurnover),
        totalAssetValue: nullableFigureFromDb(entity.totalAssetValue),
      },
    }, tx)
  })
}
